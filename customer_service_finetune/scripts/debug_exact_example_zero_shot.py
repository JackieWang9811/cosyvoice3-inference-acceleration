from pathlib import Path
import os, sys, traceback
ROOT=Path('/home/b24zll/data/wjq_data/CosyVoice')
os.environ.setdefault('PYTHONIOENCODING','UTF-8')
os.environ.setdefault('CUDA_HOME', str(ROOT/'customer_service_finetune/fake_cuda'))
sys.path.insert(0, str(ROOT/'third_party/Matcha-TTS'))
sys.path.insert(0, str(ROOT))
import torchaudio
from cosyvoice.cli.cosyvoice import AutoModel
from cosyvoice.utils.common import set_all_random_seed

out=ROOT/'customer_service_finetune/infer_outputs/debug_exact_zero_shot'
out.mkdir(parents=True, exist_ok=True)
cosyvoice=AutoModel(model_dir=str(ROOT/'pretrained_models/Fun-CosyVoice3-0.5B'), fp16=False)
prompt_wav=str(ROOT/'asset/zero_shot_prompt.wav')

cases=[
 ('example_exact', '?????<strong>??</strong>????????????', '?????????????????????????????????????????<|endofprompt|>???????????????', {}),
 ('example_no_markup', '???????????????????', '?????????????????????????????????????????<|endofprompt|>???????????????', {}),
 ('customer_default_frontend', '???????????????????????????????????????????????????????????????????', 'You are a helpful assistant.<|endofprompt|>???????????????', {}),
 ('customer_cn_prompt', '???????????????????????????????????????????????????????????????????', '?????????????????????????<|endofprompt|>???????????????', {}),
 ('customer_frontend_false', '???????????????????????????????????????????????????????????????????', 'You are a helpful assistant.<|endofprompt|>???????????????', {'text_frontend':False}),
]
for idx,(name,target,prompt,kwargs) in enumerate(cases):
    print('CASE', name, 'target_len', len(target), 'prompt_len', len(prompt), 'kwargs', kwargs, flush=True)
    set_all_random_seed(1000+idx)
    try:
        n=0
        for j,r in enumerate(cosyvoice.inference_zero_shot(target, prompt, prompt_wav, stream=False, **kwargs)):
            dur=r['tts_speech'].shape[1]/cosyvoice.sample_rate
            path=out/f'{name}_{j}.wav'
            torchaudio.save(str(path), r['tts_speech'].cpu(), cosyvoice.sample_rate)
            print('SAVED', path, f'{dur:.2f}s', r['tts_speech'].shape, flush=True)
            n+=1
        print('COUNT', n, flush=True)
    except Exception:
        traceback.print_exc()
